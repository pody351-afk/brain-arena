// هل الكلمة ممكن تتكوّن من الحروف (كل حرف مرة واحدة)؟
function wordFits(word, letters) {
  const pool = [...letters];
  for (const ch of word) { const i = pool.indexOf(ch); if (i < 0) return false; pool.splice(i, 1); }
  return true;
}
